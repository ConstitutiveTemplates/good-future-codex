"""Generate sections/MANIFEST.yml and the docs vocabulary tables.

MANIFEST.yml is a build artifact: the index consumers read, derived from
each section's front matter plus sections/VOCABULARY.yml. Never edit it by
hand; run ``just manifest`` (``python tools/manifest.py``). ``--check``
(and ``just check``) fail when the committed file or a docs table is stale.
"""

from __future__ import annotations

import re
from pathlib import Path

import yaml

from .const import GENERATED_DOCS, MANIFEST, SECTION_GLOB, SECTIONS, VOCABULARY
from .frontmatter import read_section
from .vocabulary import load_vocabulary, pack_for, when_groups

MANIFEST_SCHEMA = 2
MANIFEST_HEADER = """\
# GENERATED by tools/manifest.py -- do not edit. Run `just manifest`.
#
# The kanon distribution index, derived from the YAML front matter of every
# sections/<tier>/<slug>.md plus sections/VOCABULARY.yml. Each row says
# WHERE a section wants to land (`placement`) and UNDER WHAT ABSTRACT
# CONDITION (`when`: a condition or a list meaning "any of these"), in
# kanon's own vocabulary -- never a consumer's flag name. `pack` is `core`
# or the extension pack whose conditions alone gate the section.
# `obligations` are the law-map obligation ids the section serves; law-map
# owns their freshness. `just check` and CI fail when this file is stale.
"""

# Front matter fields copied into MANIFEST rows (prose fields -- en, sources
# -- stay in the section file).
ROW_FIELDS = ("id", "version", "status", "placement", "when", "obligations", "triggers")

VOCAB_BEGIN = "<!-- BEGIN GENERATED: when-vocabulary (tools/manifest.py from sections/MANIFEST.yml) -->"
VOCAB_END = "<!-- END GENERATED: when-vocabulary -->"
VOCAB_BLOCK_RE = re.compile(re.escape(VOCAB_BEGIN) + r".*?" + re.escape(VOCAB_END), re.DOTALL)


def _as_list(value: object) -> list[str]:
    if isinstance(value, list):
        return [str(v) for v in value]
    return [str(value)] if value is not None else []


def build_manifest(sections_dir: Path = SECTIONS, vocabulary: Path = VOCABULARY) -> dict:
    """The MANIFEST mapping: embedded vocabulary + one row per section file."""
    vocab = load_vocabulary(vocabulary)
    rows: list[dict] = []
    for path in sorted(sections_dir.glob(SECTION_GLOB)):
        front, _ = read_section(path)
        if front is None:
            continue  # the validator reports the missing front matter
        row: dict = {"id": front.get("id"), "file": path.relative_to(sections_dir).as_posix()}
        for key in ROW_FIELDS[1:]:
            if key in front:
                row[key] = front[key]
            if key == "when":
                row["pack"] = pack_for(_as_list(front.get("when")), vocab)
        rows.append(row)
    return {"schema": MANIFEST_SCHEMA, "vocabulary": vocab, "sections": rows}


class _ManifestDumper(yaml.SafeDumper):
    """Block mappings, but lists of scalars on one line (``[a, b]``)."""


def _represent_list(dumper: yaml.SafeDumper, data: list) -> yaml.Node:
    flow = all(not isinstance(item, (dict, list)) for item in data)
    return dumper.represent_sequence("tag:yaml.org,2002:seq", data, flow_style=flow)


_ManifestDumper.add_representer(list, _represent_list)


def render_manifest(manifest: dict) -> str:
    body = yaml.dump(manifest, Dumper=_ManifestDumper, sort_keys=False, allow_unicode=True, width=10_000)
    return MANIFEST_HEADER + "\n" + body


def render_vocabulary_table(manifest: dict) -> str:
    """Markdown table of the `when` vocabulary, from a MANIFEST mapping."""
    vocab = manifest["vocabulary"]
    used: dict[str, int] = {}
    for row in manifest["sections"]:
        for cond in _as_list(row.get("when")):
            used[cond] = used.get(cond, 0) + 1
    lines = [
        VOCAB_BEGIN,
        "| Group | Condition | Meaning | Sections |",
        "| --- | --- | --- | --- |",
    ]
    for kind, name, title, values in when_groups(vocab):
        label = {"general": title, "axes": f"axis: {title}", "extensions": f"extension pack `{name}`"}[kind]
        for cond, meaning in values.items():
            lines.append(f"| {label} | `{cond}` | {meaning} | {used.get(cond, 0)} |")
    lines.append("")
    lines.append("`placement`: " + " / ".join(f"`{k}` ({v})" for k, v in vocab["placement"].items()) + ".")
    lines.append("")
    lines.append("`status`: " + " / ".join(f"`{k}` ({v})" for k, v in vocab["status"].items()) + ".")
    lines.append(VOCAB_END)
    return "\n".join(lines)


def render_doc(text: str, table: str) -> str | None:
    """``text`` with its vocabulary block replaced; None when it has no markers."""
    if VOCAB_BLOCK_RE.search(text) is None:
        return None
    return VOCAB_BLOCK_RE.sub(lambda _m: table, text)


def expected_outputs(
    sections_dir: Path = SECTIONS,
    manifest_path: Path = MANIFEST,
    docs: tuple[Path, ...] = GENERATED_DOCS,
) -> dict[Path, str]:
    """Path -> expected content for MANIFEST.yml and every docs file with markers."""
    manifest = build_manifest(sections_dir)
    out = {manifest_path: render_manifest(manifest)}
    table = render_vocabulary_table(manifest)
    for doc in docs:
        if doc.is_file():
            rendered = render_doc(doc.read_text(encoding="utf-8"), table)
            if rendered is not None:
                out[doc] = rendered
    return out


def stale_outputs(outputs: dict[Path, str]) -> list[Path]:
    return [
        path for path, content in outputs.items()
        if not path.is_file() or path.read_text(encoding="utf-8") != content
    ]


def write_outputs(outputs: dict[Path, str]) -> list[Path]:
    written = stale_outputs(outputs)
    for path in written:
        path.write_text(outputs[path], encoding="utf-8")
    return written
